def cached_fetch(fetch_fn):
    """Reuse one download per symbol/configuration within a script invocation."""
    return lru_cache(maxsize=None)(fetch_fn)


def experiment_args(symbols, *, years=10, record_option=None):
    """Parse before any I/O, so every historical experiment has a safe --help."""
    parser = argparse.ArgumentParser(
        description="Explicit historical Wyckoff/P&F experiment"
    )
    parser.add_argument("--symbols", nargs="+", default=list(symbols))
    parser.add_argument("--years", type=float, default=years)
    if record_option:
        parser.add_argument(f"--{record_option}", type=Path, default=RECORD_PATH)
    args = parser.parse_args()
    if not np.isfinite(args.years) or args.years <= 0:
        parser.error("--years must be positive and finite")
    if len(args.symbols) != len(set(args.symbols)):
        parser.error("--symbols must not contain duplicates")
    return args


def session_dates(values):
    """Keep exchange-session dates, including CSVs containing mixed UTC offsets."""
    dates = pd.DatetimeIndex(
        [pd.Timestamp(v).tz_localize(None).normalize() for v in values]
    )
    if dates.hasnans:
        raise ValueError("record dates must be valid")
    return dates


def load_records(path):
    recs = pd.read_csv(path)
    required = {"sym", "date", "phase", "vol20"}
    missing = required.difference(recs.columns)
    if missing:
        raise ValueError(f"framework record CSV is missing columns: {sorted(missing)}")
    if recs.empty:
        raise ValueError("framework record CSV has no observations")
    if recs[["sym", "date"]].isna().any().any():
        raise ValueError("framework record CSV contains missing symbols or dates")
    recs["date"] = session_dates(recs["date"])
    if recs.duplicated(["sym", "date"]).any():
        raise ValueError(
            "framework record CSV contains duplicate symbol/date observations"
        )
    return recs.sort_values(["sym", "date"]).reset_index(drop=True)


def attach_returns(recs, fetch_fn, symbols, years=10):
    """Prefer returns stored alongside states; support legacy CSVs by date join."""
    if "ret" not in recs:
        print(
            "Legacy CSV: returns use newly downloaded data; regenerate records for a single snapshot."
        )
        returns = []
        for symbol in symbols:
            df = fetch_fn(symbol, years)
            returns.append(
                pd.DataFrame(
                    {
                        "date": session_dates(df.index),
                        "sym": symbol,
                        "ret": df["Close"].pct_change(fill_method=None).to_numpy(),
                    }
                )
            )
        recs = recs.merge(
            pd.concat(returns, ignore_index=True),
            on=["sym", "date"],
            how="left",
            validate="one_to_one",
        )
    recs["ret"] = pd.to_numeric(recs["ret"], errors="raise")
    recs = (
        recs[recs["sym"].isin(symbols)]
        .dropna(subset=["ret"])
        .sort_values(["sym", "date"])
    )
    if recs.empty or not np.isfinite(recs["ret"].to_numpy(dtype=float)).all():
        raise ValueError("framework records have no valid finite returns")
    return recs.reset_index(drop=True)


def lag_weights(recs, weights):
    """Lag each symbol in date order, returning weights in original row order."""
    if len(recs) != len(weights):
        raise ValueError("one weight is required for every record")
    frame = recs[["sym", "date"]].reset_index(drop=True).assign(_w=weights)
    ordered = frame.sort_values(["sym", "date"])
    shifted = ordered.groupby("sym", sort=False)["_w"].shift(1).fillna(1.0)
    return shifted.reindex(frame.index).to_numpy()


def volatility_weights(values, target, clip_lo=0.3, clip_hi=1.5):
    """Divide only valid volatilities, then clip the requested target once."""
    values = np.asarray(values, dtype=float)
    valid = np.isfinite(values) & (values > 0)
    result = np.ones_like(values)
    np.divide(target, values, out=result, where=valid)
    result[valid] = np.clip(result[valid], clip_lo, clip_hi)
    return result


def simulate_trade(df, entry_t, direction, stop, target):
    """Historical single-trade sample with shared, gap-aware OHLC exit fills."""
    from backtest import barrier_exit

    if entry_t < 0 or entry_t >= len(df):
        return None
    entry = float(df["Open"].iloc[entry_t])
    for t in range(entry_t, len(df)):
        row = df.iloc[t]
        fill = barrier_exit(
            row["Open"], row["High"], row["Low"], direction, stop, target
        )
        if fill is not None:
            price, reason = fill
            return direction * (price / entry - 1), t - entry_t, reason
    return (
        direction * (float(df["Close"].iloc[-1]) / entry - 1),
        len(df) - 1 - entry_t,
        "END",
    )


def metrics(returns, periods=252):
    """Annualized return, volatility, Sharpe and normalized peak drawdown.

    periods is a research calendar convention, not a claim of executable alpha.
    The initial capital participates in the running peak, including day one.
    """
    returns = np.asarray(returns, dtype=float)
    if len(returns) == 0 or not np.isfinite(returns).all():
        raise ValueError("metrics require nonempty, finite returns")
    equity = np.cumprod(1 + returns)
    ann = (
        float(equity[-1] ** (periods / len(returns)) - 1)
        if equity[-1] >= 0
        else float("nan")
    )
    std = float(np.std(returns, ddof=1)) if len(returns) > 1 else 0.0
    vol = std * np.sqrt(periods)
    sharpe = float(returns.mean() / std * np.sqrt(periods)) if std > 0 else 0.0
    peak = np.maximum.accumulate(np.concatenate(([1.0], equity)))[1:]
    dd = float(np.max((peak - equity) / peak))
    return ann, vol, sharpe, dd
